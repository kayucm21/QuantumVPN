def catalog(query='', group='', offset=0, limit=20):
    if not isinstance(query, str) or len(query) > 128:
        raise ValueError('invalid_roadmap_query')
    if group not in ('', *(key for key, _ in GROUPS)):
        raise ValueError('invalid_roadmap_group')
    if type(offset) is not int or not 0 <= offset <= 100:
        raise ValueError('invalid_roadmap_offset')
    if type(limit) is not int or not 1 <= limit <= 50:
        raise ValueError('invalid_roadmap_limit')
    needle = query.strip().casefold()
    counts = {status: 0 for status in STATUS_LABELS}
    rows = []
    for number, (title, description) in enumerate(_DEFINITIONS, 1):
        key = GROUPS[(number - 1) // 10][0]
        state = PROGRESS.get(number, {'status': 'planned', 'note': ''})
        counts[state['status']] += 1
        row = {'id': number, 'group': key, 'title': title, 'description': description,
               'status': state['status'], 'status_label': STATUS_LABELS[state['status']],
               'note': state['note']}
        if group and key != group:
            continue
        if needle and needle not in f"{number} {title} {description}".casefold():
            continue
        rows.append(row)
    return {'schema': 1, 'name': 'Quantum 4.0', 'scope': 'roadmap_not_release_completion',
            'total': len(_DEFINITIONS), 'matched': len(rows), 'counts': counts,
            'groups': [{'id': key, 'title': title} for key, title in GROUPS],
            'offset': offset, 'limit': limit, 'items': rows[offset:offset + limit],
            'next_offset': offset + limit if offset + limit < len(rows) else None}
